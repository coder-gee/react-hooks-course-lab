import { StrictMode } from "react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import App from "./App";
import EffectReference from "./references/EffectCleanupCheckoutReference";
import EffectExercise from "./exercises/EffectCleanupCheckoutExercise";
import { ReservationTimerLab } from "./components/ReservationTimerLab";
import { checkoutReservationTimers, createReservationTimers } from "./lib/reservationTimers";
beforeEach(() => { vi.useFakeTimers(); checkoutReservationTimers.reset(); });
afterEach(() => { cleanup(); checkoutReservationTimers.dispose(); vi.clearAllTimers(); vi.useRealTimers(); vi.restoreAllMocks(); });
const tick = (ms: number) => act(() => vi.advanceTimersByTime(ms));
const countdown = () => screen.getByLabelText("Flash sale time remaining").textContent;
const review = () => fireEvent.click(screen.getByRole("button", { name: /Review order/ }));
const edit = () => fireEvent.click(screen.getByRole("button", { name: /Edit details/ }));
it("reference clears on Review and remounts one fresh timer without losing form choices", () => {
  const view = render(<StrictMode><EffectReference /></StrictMode>);
  expect(countdown()).toBe("00:30");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
  fireEvent.click(screen.getByLabelText("Increase quantity"));
  fireEvent.change(screen.getByLabelText("Order note"), { target: { value: "Keep this note" } });
  tick(3000);
  expect(countdown()).toBe("00:27");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
  review();
  expect(screen.queryByLabelText("Flash sale time remaining")).toBeNull();
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  const ticks = checkoutReservationTimers.getSnapshot().ticks;
  tick(4000);
  expect(checkoutReservationTimers.getSnapshot().ticks).toBe(ticks);
  edit();
  expect(countdown()).toBe("00:30");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
  expect(screen.getByLabelText("Quantity").textContent).toBe("2");
  expect((screen.getByLabelText("Order note") as HTMLTextAreaElement).value).toBe("Keep this note");
  tick(31000);
  expect(countdown()).toBe("00:00");
  review(); edit();
  expect(countdown()).toBe("00:30");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
  view.unmount();
  expect(vi.getTimerCount()).toBe(0);
});
it("exercise starts inactive and preserves its supplied form and Review/Edit loop", () => {
  render(<StrictMode><EffectExercise /></StrictMode>);
  tick(5000);
  expect(countdown()).toBe("00:30");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  expect(vi.getTimerCount()).toBe(0);
  fireEvent.click(screen.getByLabelText("Increase quantity"));
  fireEvent.change(screen.getByLabelText("Order note"), { target: { value: "Keep this" } });
  review(); tick(2000);
  expect(checkoutReservationTimers.getSnapshot().ticks).toBe(0);
  edit();
  expect(countdown()).toBe("00:30");
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  expect(screen.getByLabelText("Quantity").textContent).toBe("2");
  expect((screen.getByLabelText("Order note") as HTMLTextAreaElement).value).toBe("Keep this");
});
it.each([false, true])("compact banner lifecycle and teardown, fixed=%s", fixed => {
  const view = render(<ReservationTimerLab fixed={fixed} />);
  expect(screen.queryByLabelText("Order note")).toBeNull();
  expect(screen.queryByLabelText("Increase quantity")).toBeNull();
  expect(screen.queryByRole("button", { name: /Review order/ })).toBeNull();
  tick(1000);
  expect(countdown()).toBe("00:29");
  fireEvent.click(screen.getByRole("button", { name: "Unmount timer" }));
  expect(screen.queryByLabelText("Flash sale time remaining")).toBeNull();
  const before = screen.getByLabelText("Timer ticks").textContent;
  expect(vi.getTimerCount()).toBe(fixed ? 0 : 1);
  tick(1000);
  expect(screen.getByLabelText("Timer ticks").textContent === before).toBe(fixed);
  fireEvent.click(screen.getByRole("button", { name: "Mount timer" }));
  expect(countdown()).toBe("00:30");
  expect(vi.getTimerCount()).toBe(fixed ? 1 : 2);
  view.unmount();
  expect(vi.getTimerCount()).toBe(0);
});
it("leaving the working checkout clears timers and uses no extra mount toggle", () => {
  vi.spyOn(window, "scrollTo").mockImplementation(() => {});
  window.history.replaceState({}, "", "/checkout?checkpoint=repair-sync&view=reference");
  render(<App />);
  expect(screen.queryByRole("button", { name: "Unmount checkout" })).toBeNull();
  review(); edit();
  expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
  fireEvent.click(screen.getByRole("link", { name: "Glossary" }));
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  expect(vi.getTimerCount()).toBe(0);
});
it("bounds intentionally forgotten intervals", () => {
  const timers = createReservationTimers();
  timers.setInterval(() => {}, 1000);
  tick(120000);
  expect(timers.getSnapshot().active).toBe(0);
  expect(vi.getTimerCount()).toBe(0);
});

it("inactive exercise and working reference stay correct under StrictMode", () => {
  vi.spyOn(window, "scrollTo").mockImplementation(() => {});
  window.history.replaceState({}, "", "/checkout?checkpoint=repair-sync");
  render(<StrictMode><App /></StrictMode>);
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  tick(1000); expect(countdown()).toBe("00:30");
  review(); edit();
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  tick(1000); expect(countdown()).toBe("00:30");
  fireEvent.click(screen.getByRole("button", { name: "↻ Reset" }));
  expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
  fireEvent.change(screen.getByLabelText("Checkout version"), { target: { value: "repair-sync::reference" } });
  for (let i = 0; i < 3; i++) {
    expect(checkoutReservationTimers.getSnapshot().active).toBe(1);
    tick(1000); expect(countdown()).toBe("00:29");
    review();
    expect(checkoutReservationTimers.getSnapshot().active).toBe(0);
    const ticks = screen.getByLabelText("Timer ticks").textContent;
    tick(1000); expect(screen.getByLabelText("Timer ticks").textContent).toBe(ticks);
    edit(); expect(countdown()).toBe("00:30");
  }
});
